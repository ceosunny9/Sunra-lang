/**
 * Game templates.
 *
 * `sunra slot` and `sunra baccarat` generate a complete, runnable game from a
 * one-line brief. This module extends that idea to the rest of the floor:
 * blackjack, video poker, craps, sic bo and a lottery draw, plus the two
 * mechanics that appear inside almost every real title — a progressive jackpot
 * and a multiplier ladder.
 *
 * Each template is a complete `.sun` program: a `game` block with a declared
 * `rtp`, a `spin` that resolves one unit bet (so `sunra rtp` and `sunra certify`
 * work without editing), a `main` that prints a short simulation, and `test`
 * blocks that state the rules the maths depends on. The house figures are the
 * published ones for the standard rule set quoted in each header, and the
 * simulation is what checks them.
 *
 * Templates deliberately lean on the pure runtime modules (`Deck`, `Card`,
 * `Poker`, `Dice`, `Money`, `Rtp`) rather than re-implementing rules in generated
 * source, so a rule fix lands in one place.
 */

export type TemplateId =
  | "blackjack"
  | "poker"
  | "craps"
  | "sicbo"
  | "lottery"
  | "jackpot"
  | "multiplier";

export interface GameTemplate {
  id: TemplateId;
  /** Game block name in the generated source. */
  name: string;
  /** One-line description shown by `sunra new --list`. */
  summary: string;
  /** Category, for grouping in help output. */
  category: "card" | "dice" | "lottery" | "pattern";
  /** Declared return to player of the generated game. */
  rtp: number;
  /** The complete program. */
  source: string;
}

