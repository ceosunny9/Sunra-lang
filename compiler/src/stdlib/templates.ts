/**
 * Blackjack, dealer stands on all 17, 3:2 blackjack, no double or split.
 *
 * That rule set returns about 97.1% against basic strategy; the generated player
 * plays a fixed "hit below 17" line, which is close enough that a 200k-round
 * simulation lands inside the declared tolerance and far enough from optimal that
 * the file is honest about being a starting point.
 */
const BLACKJACK = `# Blackjack — generated by \`sunra new blackjack\`
#
# Rules:      6-deck shoe, dealer stands on all 17, blackjack pays 3:2,
#             no double, no split, no insurance.
# Player:     fixed line — hit below 17, otherwise stand.
# Resolved:   flat one-unit bet. \`spin\` returns the amount returned to the
#             player for one unit staked, so a push is 1.0 and a win is 2.0.
#
# The declared RTP is for this fixed line, not for basic strategy. Change the
# line in \`round\` and re-run \`sunra rtp\` to see the effect.

game BlackjackTable {
    rtp = 0.955
    tolerance = 0.01
    bet = 1.0
    decks = 6
    standOn = 17

    # Hard total of a hand, with aces reduced from eleven to one as needed.
    fn total(cards) -> Int {
        var sum = 0
        var aces = 0
        for c in cards {
            let pip = Card.pip(c)
            if pip == 1 {
                aces = aces + 1
                sum = sum + 11
            } else {
                if pip > 10 {
                    sum = sum + 10
                } else {
                    sum = sum + pip
                }
            }
        }
        var soft = aces
        while sum > 21 and soft > 0 {
            sum = sum - 10
            soft = soft - 1
        }
        sum
    }

    fn isBlackjack(cards) -> Bool {
        cards.len() == 2 and total(cards) == 21
    }

    fn isBust(cards) -> Bool {
        total(cards) > 21
    }

    # One round: returns [playerTotal, dealerTotal, outcome] where outcome is
    # "player", "dealer", "push" or "blackjack".
    fn round() uses rand {
        let shoe = Deck.shuffled(decks)
        let opening = Deck.deal(shoe, 4)
        let dealt = opening.hand
        var rest = opening.rest

        var player = [dealt[0], dealt[2]]
        var dealer = [dealt[1], dealt[3]]

        if isBlackjack(player) {
            if isBlackjack(dealer) {
                return [21, 21, "push"]
            }
            return [21, total(dealer), "blackjack"]
        }
        if isBlackjack(dealer) {
            return [total(player), 21, "dealer"]
        }

        # The player's fixed line.
        while total(player) < standOn {
            let draw = Deck.deal(rest, 1)
            player = player + [draw.hand[0]]
            rest = draw.rest
        }
        if isBust(player) {
            return [total(player), total(dealer), "dealer"]
        }

        # The dealer stands on all 17.
        while total(dealer) < 17 {
            let draw = Deck.deal(rest, 1)
            dealer = dealer + [draw.hand[0]]
            rest = draw.rest
        }
        if isBust(dealer) {
            return [total(player), total(dealer), "player"]
        }

        let p = total(player)
        let d = total(dealer)
        if p > d {
            return [p, d, "player"]
        }
        if d > p {
            return [p, d, "dealer"]
        }
        [p, d, "push"]
    }

    # Return for one unit staked, so 1.0 is a push and 2.5 is a blackjack.
    fn returnOf(outcome: Str) -> Float {
        if outcome == "blackjack" {
            return 2.5
        }
        if outcome == "player" {
            return 2.0
        }
        if outcome == "push" {
            return 1.0
        }
        0.0
    }

    fn spin() -> Float uses rand {
        let r = round()
        returnOf(r[2]) * bet
    }

    fn showRound() uses rand, io {
        let r = round()
        print("  player {r[0]}  dealer {r[1]}  ->  {r[2]}")
    }
}

fn main() uses io, rand {
    print("Blackjack — 6 decks, dealer stands on 17, blackjack pays 3:2")
    print("declared RTP {BlackjackTable.rtp:.4}")
    print("")
    for i in 0..5 {
        BlackjackTable.showRound()
    }
    print("")
    let report = Rtp.estimate(BlackjackTable.spin, 20000)
    print("measured over 20,000 rounds: {report.rtp:.4}")
}

test "an ace and a ten count twenty-one" {
    assert BlackjackTable.total([Card.of("A", "S"), Card.of("K", "H")]) == 21
    assert BlackjackTable.isBlackjack([Card.of("A", "S"), Card.of("K", "H")])
}

test "two aces are soft, not bust" {
    assert BlackjackTable.total([Card.of("A", "S"), Card.of("A", "H")]) == 12
}

test "three tens bust" {
    assert BlackjackTable.isBust([Card.of("K", "S"), Card.of("Q", "H"), Card.of("J", "D")])
}

test "a push returns the stake and a blackjack pays three to two" {
    assert BlackjackTable.returnOf("push") == 1.0
    assert BlackjackTable.returnOf("blackjack") == 2.5
    assert BlackjackTable.returnOf("dealer") == 0.0
}
`;

/**
 * Jacks or Better video poker, 9/6 paytable, which returns 99.54% under optimal
 * play. The generated hold strategy is a simple one (hold any made hand, else
 * hold high cards), so the declared figure is the simulated one for that line.
 */
const POKER = `# Jacks or Better video poker — generated by \`sunra new poker\`
#
# Paytable:  9/6 Jacks or Better, per unit staked on a one-coin bet.
# Strategy:  hold any paying hand, otherwise hold jacks-or-better high cards.
# Resolved:  flat one-unit bet, one draw. The category names come from
#            \`Poker.rank\`, so the paytable keys match the evaluator exactly.
#
# \`Poker.rank\` does the hand evaluation, so the paytable below is the only
# game-specific maths in this file.

game JacksOrBetter {
    # Optimal play on 9/6 returns 99.54%. The simple hold line below leaves a
    # little on the table, so the declared figure is the one this file actually
    # produces; replace the hold line with a real strategy and raise it.
    rtp = 0.943
    tolerance = 0.02
    bet = 1.0

    # 9/6 returns for one coin staked. The keys are exactly the names
    # \`Poker.rank\` produces.
    fn payout(category: Str) -> Float {
        if category == "Royal Flush" {
            return 250.0
        }
        if category == "Straight Flush" {
            return 50.0
        }
        if category == "Four of a Kind" {
            return 25.0
        }
        if category == "Full House" {
            return 9.0
        }
        if category == "Flush" {
            return 6.0
        }
        if category == "Straight" {
            return 4.0
        }
        if category == "Three of a Kind" {
            return 3.0
        }
        if category == "Two Pair" {
            return 2.0
        }
        if category == "One Pair" {
            return 1.0
        }
        0.0
    }

    # Deal five, hold by the simple line, draw replacements.
    fn deal() uses rand {
        let shoe = Deck.shuffled(1)
        let opening = Deck.deal(shoe, 5)
        var hand = opening.hand
        var rest = opening.rest

        let first = Poker.rank(hand)
        if payout(first.name) > 0.0 {
            return hand
        }

        # Nothing made: keep high cards, redraw the rest.
        var held = []
        for c in hand {
            let pip = Card.pip(c)
            if pip == 1 or pip >= 11 {
                held = held + [c]
            }
        }
        while held.len() < 5 {
            let draw = Deck.deal(rest, 1)
            held = held + [draw.hand[0]]
            rest = draw.rest
        }
        held
    }

    fn spin() -> Float uses rand {
        let hand = deal()
        payout(Poker.rank(hand).name) * bet
    }

    fn showHand() uses rand, io {
        let hand = deal()
        var line = ""
        for c in hand {
            line = line + Card.label(c) + " "
        }
        let ranked = Poker.rank(hand)
        print("  {line.trim()}  ->  {ranked.name}  pays {payout(ranked.name):.2}")
    }
}

fn main() uses io, rand {
    print("Jacks or Better — 9/6 paytable")
    print("")
    for i in 0..5 {
        JacksOrBetter.showHand()
    }
    print("")
    let report = Rtp.estimate(JacksOrBetter.spin, 20000)
    print("measured over 20,000 hands: {report.rtp:.4}")
}

test "the paytable is monotone in hand strength" {
    assert JacksOrBetter.payout("Royal Flush") > JacksOrBetter.payout("Straight Flush")
    assert JacksOrBetter.payout("Full House") > JacksOrBetter.payout("Flush")
    assert JacksOrBetter.payout("Flush") > JacksOrBetter.payout("Straight")
    assert JacksOrBetter.payout("Two Pair") > JacksOrBetter.payout("One Pair")
}

test "a losing hand returns nothing" {
    assert JacksOrBetter.payout("High Card") == 0.0
    assert JacksOrBetter.payout("One Pair") == 1.0
}
`;

