/** Every template, in help order. */
export function listTemplates(): GameTemplate[] {
  return TEMPLATES;
}

/** Look up a template by id. Returns null for an unknown id. */
export function findTemplate(id: string): GameTemplate | null {
  const wanted = id.trim().toLowerCase().replace(/[\s_-]/g, "");
  return TEMPLATES.find((template) => template.id === wanted) ?? null;
}

/** The ids a caller may pass, for error messages and shell completion. */
export function templateIds(): TemplateId[] {
  return TEMPLATES.map((template) => template.id);
}
