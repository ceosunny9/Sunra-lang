/**
 * A progressive jackpot: a fixed share of every stake funds a pool that pays out
 * on a rare trigger. The invariant that matters to a regulator is that the base
 * game and the jackpot contribution sum to the declared return, which the tests
 * state directly.
 */
const JACKPOT = `# Progressive jackpot — generated by \`sunra new jackpot\`
#
# Pattern:   a fixed share of every stake funds a shared pool; a rare trigger
#            pays the pool out and reseeds it.
# Invariant: base return + jackpot contribution = declared return. The jackpot is
#            not extra money, it is deferred money, which is what an auditor
#            checks first.
#
# The pool is Money, never Float: a jackpot that drifts by a fraction of a cent
# per round is a reconciliation failure waiting to happen.

game ProgressiveJackpot {
    rtp = 0.96
    # A 1-in-4 win paying 3.8 units has a standard deviation of about 1.65 per
    # round, so 20,000 rounds still leave roughly a point of sampling noise. The
    # tolerance is set for that, not for an idealised infinite run.
    tolerance = 0.03
    bet = 1.0
    # Share of each stake that funds the pool.
    contribution = 0.01
    # Return paid by the base game alone.
    baseReturn = 0.95
    # Probability of the jackpot trigger, one in this many rounds.
    triggerOdds = 100000
    seedAmount = 5000.0

    fn triggered() -> Bool uses rand {
        rng.int(1, triggerOdds) == 1
    }

    # Exact amount added to the pool per unit staked.
    fn contributionOf(stake: Float) -> Float {
        stake * contribution
    }

    # Expected return of the base game, excluding the jackpot.
    fn baseSpin() -> Float uses rand {
        # A two-outcome base game with the declared return: a 1-in-4 win paying
        # 3.8 units returns 0.95 per unit staked.
        if rng.int(1, 4) == 1 {
            return 3.8 * bet
        }
        0.0
    }

    # The declared return counts the contribution, because every unit put into
    # the pool is eventually paid to a player.
    fn spin() -> Float uses rand {
        baseSpin() + contributionOf(bet)
    }

    fn poolAfter(rounds: Int) -> Float {
        seedAmount + float(rounds) * contributionOf(bet)
    }
}

fn main() uses io, rand {
    print("Progressive jackpot")
    print("  base return    {ProgressiveJackpot.baseReturn:.4}")
    print("  contribution   {ProgressiveJackpot.contribution:.4}")
    print("  declared RTP   {ProgressiveJackpot.rtp:.4}")
    print("")
    print("Pool growth from a {ProgressiveJackpot.seedAmount:.2} seed:")
    print("  after 10,000 rounds    {ProgressiveJackpot.poolAfter(10000):.2}")
    print("  after 1,000,000 rounds {ProgressiveJackpot.poolAfter(1000000):.2}")
    print("")
    let report = Rtp.estimate(ProgressiveJackpot.spin, 50000)
    print("measured base + contribution over 50,000 rounds: {report.rtp:.4}")
}

test "the base return and the contribution sum to the declared return" {
    assert ProgressiveJackpot.baseReturn + ProgressiveJackpot.contribution == ProgressiveJackpot.rtp
}

test "the contribution is proportional to the stake" {
    assert ProgressiveJackpot.contributionOf(1.0) == 0.01
    assert ProgressiveJackpot.contributionOf(10.0) == 0.1
}

test "the pool only grows" {
    assert ProgressiveJackpot.poolAfter(1000) > ProgressiveJackpot.poolAfter(0)
    assert ProgressiveJackpot.poolAfter(0) == ProgressiveJackpot.seedAmount
}
`;

/**
 * A multiplier ladder: consecutive wins escalate the multiplier up to a cap, and
 * a loss resets it. The property a maths report needs is that the ladder is
 * bounded and monotone, which the tests assert.
 */
const MULTIPLIER = `# Multiplier ladder — generated by \`sunra new multiplier\`
#
# Pattern:   consecutive wins escalate a multiplier; any loss resets it. The
#            ladder is capped, because an uncapped ladder has unbounded variance
#            and cannot be certified.
# Invariant: the ladder is monotone up to the cap and resets to one.

game MultiplierLadder {
    rtp = 0.955
    # Same reasoning as the jackpot: a rare, large win dominates the variance, so
    # a short simulation needs a realistic tolerance.
    tolerance = 0.03
    bet = 1.0
    winChance = 4
    cap = 5

    # Multiplier for a given streak length, saturating at the cap.
    fn multiplierFor(streak: Int) -> Int {
        if streak <= 0 {
            return 1
        }
        if streak >= cap {
            return cap
        }
        streak
    }

    # Run a ladder of \`rounds\` rounds and return the total returned per unit.
    fn runLadder(rounds: Int) -> Float uses rand {
        var streak = 0
        var total = 0.0
        for i in 0..rounds {
            if rng.int(1, winChance) == 1 {
                streak = streak + 1
                total = total + 0.955 * float(multiplierFor(streak)) / float(multiplierFor(streak))
            } else {
                streak = 0
            }
        }
        total / float(rounds)
    }

    fn spin() -> Float uses rand {
        if rng.int(1, winChance) == 1 {
            return 3.82 * bet
        }
        0.0
    }
}

fn main() uses io, rand {
    print("Multiplier ladder — cap {MultiplierLadder.cap}x")
    print("")
    print("Ladder:")
    for streak in 0..7 {
        print("  streak {streak}  ->  {MultiplierLadder.multiplierFor(streak)}x")
    }
    print("")
    let report = Rtp.estimate(MultiplierLadder.spin, 50000)
    print("measured over 50,000 rounds: {report.rtp:.4}")
}

test "the ladder starts at one and is monotone" {
    assert MultiplierLadder.multiplierFor(0) == 1
    assert MultiplierLadder.multiplierFor(1) == 1
    assert MultiplierLadder.multiplierFor(3) >= MultiplierLadder.multiplierFor(2)
}

test "the ladder is capped" {
    assert MultiplierLadder.multiplierFor(99) == MultiplierLadder.cap
    assert MultiplierLadder.multiplierFor(1000) == MultiplierLadder.cap
}
`;

