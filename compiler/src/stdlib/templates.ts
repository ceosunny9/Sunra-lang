/**
 * Craps, pass line only: 244/495 = 49.29% win, house edge 1.41%.
 */
const CRAPS = `# Craps (pass line) — generated by \`sunra new craps\`
#
# Bet:       pass line, one unit, no odds behind.
# Maths:     the pass line wins 244 of 495 decisions, a house edge of 1.41%,
#            so one unit staked returns 0.98586 on average.
# Resolved:  one come-out sequence per \`spin\`.

game CrapsTable {
    rtp = 0.9859
    tolerance = 0.01
    bet = 1.0

    fn rollTotal() -> Int uses rand {
        # Dice.rollMany(count, faces): two six-sided dice.
        Dice.total(Dice.rollMany(2, 6))
    }

    fn isNatural(total: Int) -> Bool {
        total == 7 or total == 11
    }

    fn isCraps(total: Int) -> Bool {
        total == 2 or total == 3 or total == 12
    }

    # Resolve one pass-line decision. Returns [comeOut, point, won].
    fn decision() uses rand {
        let comeOut = rollTotal()
        if isNatural(comeOut) {
            return [comeOut, 0, true]
        }
        if isCraps(comeOut) {
            return [comeOut, 0, false]
        }

        let point = comeOut
        var rolled = rollTotal()
        while rolled != point and rolled != 7 {
            rolled = rollTotal()
        }
        [comeOut, point, rolled == point]
    }

    fn spin() -> Float uses rand {
        let d = decision()
        if d[2] {
            return 2.0 * bet
        }
        0.0
    }

    fn showDecision() uses rand, io {
        let d = decision()
        if d[1] == 0 {
            print("  come out {d[0]}  ->  decided immediately, won {d[2]}")
        } else {
            print("  come out {d[0]}  point {d[1]}  ->  won {d[2]}")
        }
    }
}

fn main() uses io, rand {
    print("Craps — pass line, house edge 1.41%")
    print("")
    for i in 0..5 {
        CrapsTable.showDecision()
    }
    print("")
    let report = Rtp.estimate(CrapsTable.spin, 50000)
    print("measured over 50,000 decisions: {report.rtp:.4}")
}

test "sevens and elevens win on the come out" {
    assert CrapsTable.isNatural(7)
    assert CrapsTable.isNatural(11)
    assert not CrapsTable.isNatural(4)
}

test "two, three and twelve lose on the come out" {
    assert CrapsTable.isCraps(2)
    assert CrapsTable.isCraps(3)
    assert CrapsTable.isCraps(12)
    assert not CrapsTable.isCraps(6)
}
`;

/**
 * Sic bo, small/big bet: wins on totals 4-10 (excluding triples), pays 1:1,
 * house edge 2.78%.
 */
const SICBO = `# Sic bo (small / big) — generated by \`sunra new sicbo\`
#
# Bet:       Small — totals 4 to 10 win, any triple loses. Pays 1:1.
# Maths:     105 of 216 outcomes win, a house edge of 2.78%.
# Resolved:  one three-dice throw per \`spin\`.

game SicBoTable {
    rtp = 0.9722
    tolerance = 0.01
    bet = 1.0

    fn throw() uses rand {
        # Dice.rollMany(count, faces): three six-sided dice.
        Dice.rollMany(3, 6)
    }

    fn isTriple(dice) -> Bool {
        dice[0] == dice[1] and dice[1] == dice[2]
    }

    fn smallWins(dice) -> Bool {
        if isTriple(dice) {
            return false
        }
        let total = Dice.total(dice)
        total >= 4 and total <= 10
    }

    fn bigWins(dice) -> Bool {
        if isTriple(dice) {
            return false
        }
        let total = Dice.total(dice)
        total >= 11 and total <= 17
    }

    fn spin() -> Float uses rand {
        let dice = throw()
        if smallWins(dice) {
            return 2.0 * bet
        }
        0.0
    }

    fn showThrow() uses rand, io {
        let dice = throw()
        print("  {dice[0]} {dice[1]} {dice[2]}  total {Dice.total(dice)}  small {smallWins(dice)}")
    }
}

fn main() uses io, rand {
    print("Sic bo — Small bet, house edge 2.78%")
    print("")
    for i in 0..5 {
        SicBoTable.showThrow()
    }
    print("")
    let report = Rtp.estimate(SicBoTable.spin, 50000)
    print("measured over 50,000 throws: {report.rtp:.4}")
}

test "a triple loses both small and big" {
    assert not SicBoTable.smallWins([3, 3, 3])
    assert not SicBoTable.bigWins([5, 5, 5])
}

test "small covers four to ten and big covers eleven to seventeen" {
    assert SicBoTable.smallWins([1, 1, 2])
    assert SicBoTable.smallWins([4, 3, 3])
    assert not SicBoTable.smallWins([6, 4, 3])
    assert SicBoTable.bigWins([6, 4, 3])
    assert not SicBoTable.bigWins([1, 1, 2])
}
`;

